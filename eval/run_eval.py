"""Evaluate readmit.

1. Score correctness: 8 encounters whose LACE and HOSPITAL components were computed
   by hand from the published point tables (eval/score_cases.json).
2. Extraction: 6 synthetic discharge summaries with gold inputs (eval/notes_gold.json).
   Reports field accuracy, Charlson category precision/recall, and how often the
   extracted inputs reproduce the gold LACE and HOSPITAL totals.

  python eval/run_eval.py [--llm] [--check]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent / "src"))

from readmit.extract import extract_llm, extract_rules  # noqa: E402
from readmit.pipeline import encounter_from_dict  # noqa: E402
from readmit.scores import effective_categories, hospital, lace  # noqa: E402

DEFAULTS = {"ed_visits_6mo": 0, "admissions_12mo": 0, "had_procedure": False, "oncology_discharge": False}


def eval_scores():
    cases = json.loads((ROOT / "score_cases.json").read_text())
    failures, bad = [], set()
    for c in cases:
        e = encounter_from_dict({"id": c["id"], **c["encounter"]})
        lc, hs = lace(e), hospital(e)
        got = {"lace": {**{k: getattr(lc, k) for k in "LACE"}, "total": lc.total},
               "hospital": {**{k: getattr(hs, k) for k in "HOSPIAL"}, "total": hs.total}}
        for score in ("lace", "hospital"):
            for k, v in c["expected"][score].items():
                if got[score][k] != v:
                    failures.append(f"{c['id']} {score}.{k}: expected {v}, got {got[score][k]}")
                    bad.add((c["id"], score))
    return len(cases), failures, len(bad)


def _totals(fields: dict, cats):
    f = {**DEFAULTS, **fields}
    try:
        e = encounter_from_dict({"id": "x", **{k: v for k, v in f.items() if k not in ("admission_date",
                                                                                    "discharge_date")},
                                 "charlson_categories": list(cats)})
        lt = lace(e).total
    except (TypeError, ValueError):
        return None, None
    try:
        ht = hospital(e).total
    except (TypeError, ValueError):
        ht = None
    return lt, ht


def eval_extraction(method: str, client=None):
    gold = json.loads((ROOT / "notes_gold.json").read_text())
    field_ok = field_n = tp = fp = fn = lace_ok = hosp_ok = 0
    errors = []
    for nid, g in sorted(gold.items()):
        text = (ROOT / "notes" / f"{nid}.txt").read_text()
        fields, cats = extract_rules(text) if method == "rules" else extract_llm(text, client)
        for k, v in g["fields"].items():
            field_n += 1
            got = fields.get(k, DEFAULTS.get(k))
            if got is not None and float(got) == float(v):
                field_ok += 1
            else:
                errors.append(f"{nid} {k}: expected {v}, got {fields.get(k, '(missing)')}")
        pc, gc = effective_categories(cats), effective_categories(g["charlson"])
        tp, fp, fn = tp + len(pc & gc), fp + len(pc - gc), fn + len(gc - pc)
        errors += [f"{nid} charlson extra: {c}" for c in sorted(pc - gc)]
        errors += [f"{nid} charlson missed: {c}" for c in sorted(gc - pc)]
        gl, gh = _totals(g["fields"], g["charlson"])
        pl, ph = _totals(fields, cats)
        lace_ok += pl == gl
        hosp_ok += ph == gh
    n = len(gold)
    p = tp / (tp + fp) if tp + fp else 1.0
    r = tp / (tp + fn) if tp + fn else 1.0
    return {"field_accuracy": field_ok / field_n, "charlson_precision": p, "charlson_recall": r,
            "lace_exact": lace_ok / n, "hospital_exact": hosp_ok / n, "errors": errors, "n": n}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--llm", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    n_cases, failures, n_bad = eval_scores()
    ext = {"rules": eval_extraction("rules")}
    if args.llm:
        from readmit.llm import client_from_env
        ext["llm"] = eval_extraction("llm", client_from_env())

    out = ["# Evaluation results", "", "Generated by `python eval/run_eval.py`. All data is synthetic.", "",
           f"## Score implementation ({n_cases} hand-computed encounters)", "",
           f"{n_cases * 2 - n_bad} of {n_cases * 2} LACE/HOSPITAL scores match the hand calculation "
           "on every component.", ""]
    out += [f"- {f}" for f in failures] or ["No component mismatches."]
    out += ["", f"## Extraction from discharge summaries ({ext['rules']['n']} notes)", "",
            "| Method | Field accuracy | Charlson precision | Charlson recall | LACE total exact "
            "| HOSPITAL total exact |",
            "|---|---|---|---|---|---|"]
    for m, r in ext.items():
        out.append(f"| {m} | {r['field_accuracy']:.2f} | {r['charlson_precision']:.2f} | "
                   f"{r['charlson_recall']:.2f} | {r['lace_exact']:.2f} | {r['hospital_exact']:.2f} |")
    if "llm" not in ext:
        out.append("| llm | not run here: requires credentials. Run `python eval/run_eval.py --llm` | | | | |")
    for m, r in ext.items():
        out += ["", f"### {m} errors", ""] + ([f"- {e}" for e in r["errors"]] or ["- none"])
    (ROOT / "RESULTS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    if args.check:
        base = json.loads((ROOT / "baseline.json").read_text())
        if failures or ext["rules"]["field_accuracy"] < base["rules_field_accuracy"]:
            print("REGRESSION", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
